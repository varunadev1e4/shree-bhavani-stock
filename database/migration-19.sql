-- Lets the golden-file restore put your own records back with their original numbers (so staff entries stay linked to staff, etc.).
alter table temp_bills        alter column id set generated by default;
alter table employees         alter column id set generated by default;
alter table emp_entries       alter column id set generated by default;
alter table expenses          alter column id set generated by default;
alter table directory         alter column id set generated by default;
alter table directory_people  alter column id set generated by default;
alter table temp_returns      alter column id set generated by default;
alter table temp_collections  alter column id set generated by default;

-- After a restore the counters must continue after the highest restored number. Only the restore script (service key) may call this.
create or replace function reset_sequences() returns void language plpgsql security definer set search_path = public as $$
declare t text;
begin
  foreach t in array array['temp_bills','employees','emp_entries','expenses','directory','directory_people','temp_returns','temp_collections'] loop
    execute format('select setval(pg_get_serial_sequence(%L, ''id''), greatest(coalesce((select max(id) from %I), 0), 1), (select count(*) > 0 from %I))', t, t, t);
  end loop;
end $$;
revoke execute on function reset_sequences() from public, anon, authenticated;
grant execute on function reset_sequences() to service_role;
