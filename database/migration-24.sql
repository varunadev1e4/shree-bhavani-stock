-- Update 24: shared shop fund for employee expenses. Run ONCE after migration-23.sql. Safe to run again. For BOTH shops.
-- The owner adds money to the fund; every expense an employee logs is deducted; everyone sees the same balance.
create table if not exists shop_fund (
  id bigint generated by default as identity primary key,
  d date not null default current_date,
  amount numeric not null check (amount > 0),
  note text,
  created_at timestamptz default now()
);
alter table shop_fund enable row level security;
drop policy if exists "fund owner" on shop_fund;
create policy "fund owner" on shop_fund for all to authenticated using (is_owner()) with check (is_owner());

-- Balance = money added - expenses logged by employees since the first top-up.
-- Employees get only this one number (they cannot read the top-up list or other people's entries).
create or replace function fund_balance() returns numeric language sql stable security definer set search_path = public as $$
  select case when is_owner() or is_staff() then
    coalesce((select sum(amount) from shop_fund), 0)
    - coalesce((select sum(amount) from expenses where emp_id is not null and d >= (select min(d) from shop_fund)), 0)
  end
$$;
revoke execute on function fund_balance() from public, anon;
grant execute on function fund_balance() to authenticated;

create or replace function reset_sequences() returns void language plpgsql security definer set search_path = public as $$
declare t text;
begin
  foreach t in array array['temp_bills','employees','emp_entries','expenses','directory','directory_people','temp_returns','temp_collections','trips','emp_cash','app_roles','shop_fund'] loop
    execute format('select setval(pg_get_serial_sequence(%L, ''id''), greatest(coalesce((select max(id) from %I), 0), 1), (select count(*) > 0 from %I))', t, t, t);
  end loop;
end $$;
revoke execute on function reset_sequences() from public, anon, authenticated;
grant execute on function reset_sequences() to service_role;
-- Done. You should see "Success. No rows returned".
