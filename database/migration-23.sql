-- Update 23: employee logins (expenses, trips, own attendance only), cash in hand, trips, advance auto-cut, leave balance.
-- Run ONCE in Supabase > SQL Editor. Safe to run again. For BOTH shops.
--
-- How the safety works: every login must have a row in app_roles.
--   owner = sees everything (all logins that exist today are made owners by this script)
--   staff = linked to one employee; can ONLY add own expenses / trips and read own attendance and cash
--   no row = sees nothing
-- This is enforced inside the database, so hiding screens is not what protects your data.

-- ---------- 1. Roles ----------
create table if not exists app_roles (
  id bigint generated by default as identity primary key,
  email text not null unique,
  role text not null check (role in ('owner','staff')),
  emp_id bigint references employees(id) on delete set null,
  created_at timestamptz default now()
);
alter table app_roles enable row level security;

-- Everyone who can log in today becomes an owner (so you are never locked out)
insert into app_roles (email, role)
select lower(email), 'owner' from auth.users where email is not null
on conflict (email) do nothing;

create or replace function my_email() returns text language sql stable as
$$ select lower(coalesce(auth.jwt() ->> 'email', '')) $$;
create or replace function is_owner() returns boolean language sql stable security definer set search_path = public as
$$ select exists (select 1 from app_roles where email = my_email() and role = 'owner') $$;
create or replace function is_staff() returns boolean language sql stable security definer set search_path = public as
$$ select exists (select 1 from app_roles where email = my_email() and role = 'staff') $$;
create or replace function my_emp() returns bigint language sql stable security definer set search_path = public as
$$ select emp_id from app_roles where email = my_email() and role = 'staff' limit 1 $$;

drop policy if exists "roles read" on app_roles;
drop policy if exists "roles owner write" on app_roles;
create policy "roles read" on app_roles for select to authenticated using (email = my_email() or is_owner());
create policy "roles owner write" on app_roles for all to authenticated using (is_owner()) with check (is_owner());

-- ---------- 2. New columns and tables ----------
alter table employees add column if not exists adv_cut numeric default 0;        -- advance cut per month (0 = manual)
alter table employees add column if not exists adv_cut_from date;                -- auto cut starts from this month
alter table employees add column if not exists leave_quota numeric default 0;    -- paid leaves per financial year (0 = not tracked)
alter table employees add column if not exists leave_date date;                  -- last working day (salary stops after it)

create table if not exists trips (
  id bigint generated by default as identity primary key,
  emp_id bigint not null references employees(id) on delete cascade,
  city text not null, purpose text,
  start_d date not null default current_date, end_d date,
  status text not null default 'open',            -- open | closed
  note text,
  created_by uuid default auth.uid(),
  created_at timestamptz default now()
);
create index if not exists trips_emp on trips(emp_id, start_d);

create table if not exists emp_cash (               -- cash given to an employee for expenses / returned by them
  id bigint generated by default as identity primary key,
  emp_id bigint not null references employees(id) on delete cascade,
  d date not null default current_date,
  kind text not null check (kind in ('given','returned')),
  amount numeric not null, note text,
  trip_id bigint references trips(id) on delete set null,
  created_at timestamptz default now()
);
create index if not exists emp_cash_emp on emp_cash(emp_id, d);

alter table expenses add column if not exists emp_id bigint references employees(id) on delete set null;
alter table expenses add column if not exists trip_id bigint references trips(id) on delete set null;
alter table expenses add column if not exists created_by uuid default auth.uid();
alter table expenses add column if not exists photo text;
create index if not exists expenses_emp on expenses(emp_id, d);
create index if not exists expenses_trip on expenses(trip_id);

-- ---------- 3. Lock every other table to owners only ----------
do $$
declare t text;
begin
  for t in select tablename from pg_tables where schemaname = 'public'
           and tablename not in ('app_roles','employees','emp_entries','expenses','trips','emp_cash') loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "owner only" on %I', t);
    execute format('create policy "owner only" on %I as restrictive for all to authenticated using (is_owner()) with check (is_owner())', t);
  end loop;
  -- views must obey the same rules (otherwise a view would leak the stock to staff)
  for t in select viewname from pg_views where schemaname = 'public' loop
    execute format('alter view %I set (security_invoker = true)', t);
  end loop;
end $$;

-- ---------- 4. Staff-related tables: owner everything, staff only their own ----------
alter table employees enable row level security;  alter table emp_entries enable row level security;
alter table expenses enable row level security;   alter table trips enable row level security;
alter table emp_cash enable row level security;

drop policy if exists "emp all" on employees;           drop policy if exists "ent all" on emp_entries;
drop policy if exists "exp all" on expenses;            drop policy if exists "app all" on employees;
drop policy if exists "app all" on emp_entries;         drop policy if exists "app all" on expenses;
drop policy if exists "emp owner" on employees;         drop policy if exists "emp staff read" on employees;
drop policy if exists "ent owner" on emp_entries;       drop policy if exists "ent staff read" on emp_entries;
drop policy if exists "exp owner" on expenses;          drop policy if exists "exp staff read" on expenses;
drop policy if exists "exp staff add" on expenses;      drop policy if exists "exp staff edit" on expenses;
drop policy if exists "exp staff delete" on expenses;
drop policy if exists "trip owner" on trips;            drop policy if exists "trip staff read" on trips;
drop policy if exists "trip staff add" on trips;        drop policy if exists "trip staff edit" on trips;
drop policy if exists "cash owner" on emp_cash;         drop policy if exists "cash staff read" on emp_cash;

create policy "emp owner" on employees for all to authenticated using (is_owner()) with check (is_owner());
create policy "emp staff read" on employees for select to authenticated using (is_staff() and id = my_emp());

create policy "ent owner" on emp_entries for all to authenticated using (is_owner()) with check (is_owner());
create policy "ent staff read" on emp_entries for select to authenticated
  using (is_staff() and emp_id = my_emp() and kind in ('absent','half','paidleave'));

create policy "exp owner" on expenses for all to authenticated using (is_owner()) with check (is_owner());
create policy "exp staff read" on expenses for select to authenticated using (is_staff() and emp_id = my_emp());
create policy "exp staff add" on expenses for insert to authenticated
  with check (is_staff() and emp_id = my_emp() and created_by = auth.uid()
              and (trip_id is null or exists (select 1 from trips x where x.id = trip_id and x.emp_id = my_emp())));
create policy "exp staff edit" on expenses for update to authenticated
  using (is_staff() and emp_id = my_emp() and created_by = auth.uid() and created_at > now() - interval '1 day')
  with check (is_staff() and emp_id = my_emp() and created_by = auth.uid());
create policy "exp staff delete" on expenses for delete to authenticated
  using (is_staff() and emp_id = my_emp() and created_by = auth.uid() and created_at > now() - interval '1 day');

create policy "trip owner" on trips for all to authenticated using (is_owner()) with check (is_owner());
create policy "trip staff read" on trips for select to authenticated using (is_staff() and emp_id = my_emp());
create policy "trip staff add" on trips for insert to authenticated with check (is_staff() and emp_id = my_emp() and created_by = auth.uid());
create policy "trip staff edit" on trips for update to authenticated using (is_staff() and emp_id = my_emp()) with check (is_staff() and emp_id = my_emp());

create policy "cash owner" on emp_cash for all to authenticated using (is_owner()) with check (is_owner());
create policy "cash staff read" on emp_cash for select to authenticated using (is_staff() and emp_id = my_emp());

-- ---------- 5. Bill photos (private bucket, one folder per employee) ----------
do $$
begin
  if to_regclass('storage.objects') is not null then
    insert into storage.buckets (id, name, public) values ('expense-bills', 'expense-bills', false) on conflict (id) do nothing;
    drop policy if exists "bills owner" on storage.objects;
    drop policy if exists "bills staff add" on storage.objects;
    drop policy if exists "bills staff read" on storage.objects;
    create policy "bills owner" on storage.objects for all to authenticated
      using (bucket_id = 'expense-bills' and is_owner()) with check (bucket_id = 'expense-bills' and is_owner());
    create policy "bills staff add" on storage.objects for insert to authenticated
      with check (bucket_id = 'expense-bills' and is_staff() and (storage.foldername(name))[1] = my_emp()::text);
    create policy "bills staff read" on storage.objects for select to authenticated
      using (bucket_id = 'expense-bills' and is_staff() and (storage.foldername(name))[1] = my_emp()::text);
  end if;
end $$;

-- ---------- 6. Backup restore helper now knows the new tables ----------
create or replace function reset_sequences() returns void language plpgsql security definer set search_path = public as $$
declare t text;
begin
  foreach t in array array['temp_bills','employees','emp_entries','expenses','directory','directory_people','temp_returns','temp_collections','trips','emp_cash','app_roles'] loop
    execute format('select setval(pg_get_serial_sequence(%L, ''id''), greatest(coalesce((select max(id) from %I), 0), 1), (select count(*) > 0 from %I))', t, t, t);
  end loop;
end $$;
revoke execute on function reset_sequences() from public, anon, authenticated;
grant execute on function reset_sequences() to service_role;

